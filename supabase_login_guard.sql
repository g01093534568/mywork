-- 무엇이 문제였나:
--   verify_login 이 빈 값끼리를 "일치"로 봅니다. 사원번호와 비밀번호를 모두
--   비운 채 호출하면, 저장된 값도 비어 있는 행이 있을 경우 그 계정으로 들어갑니다.
--
--     POST /rest/v1/rpc/verify_login
--     {"p_facility":"어떤조직","p_empno":"","p_pw_hash":"","p_pw_plain":""}
--     → {"id":"...","role":"user", ...}     ← 통과
--
--   로그인 화면은 사원번호 6자리를 요구하지만 그 검사는 브라우저에서만 합니다.
--   REST 로 함수를 직접 부르면 지나갑니다.
--
-- 지금 상태 (점검함):
--   전체 34개 계정에 대해 빈 비밀번호로 로그인을 시도해 봤고 모두 실패했습니다.
--   즉 저장된 비밀번호가 빈 행은 하나도 없습니다. 당장 뚫린 곳은 없습니다.
--
-- 왜 함수를 고치지 않는가:
--   함수 본문을 모르는 채 덮어쓰면 전 직원이 로그인하지 못할 수 있습니다.
--   비밀번호가 빈 행이 아예 못 생기게 막으면, 함수를 건드리지 않고도
--   그 구멍은 닫힙니다 — 빈 값끼리 일치할 상대가 없어지기 때문입니다.
--
-- 되돌리려면:
--   ALTER TABLE users DROP CONSTRAINT users_pw_nonempty;
-- ============================================================

ALTER TABLE users
  ADD CONSTRAINT users_pw_nonempty CHECK (패스워드 <> '');


-- ── 확인 ────────────────────────────────────────────────────
-- (가) 제약이 걸렸는지
SELECT conname AS 제약, pg_get_constraintdef(oid) AS 내용
  FROM pg_constraint
 WHERE conrelid = 'public.users'::regclass AND conname = 'users_pw_nonempty';

-- (나) 실제로 막히는지 — 아래는 반드시 실패해야 정상입니다(23514 check violation).
--      실행해 보고 오류가 나면 제대로 걸린 겁니다. 성공하면 그 행을 지우세요.
